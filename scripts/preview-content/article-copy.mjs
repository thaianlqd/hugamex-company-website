const text = (value) => ({ type: "text", text: value });
const paragraph = (value) => ({ type: "paragraph", content: [text(value)] });
export function enrichArticle(document, key, locale) {
  const sections = additions[key]?.[locale];
  if (!sections) return document;
  const [takeaway, ...body] = sections;
  return {
    type: "doc",
    content: [
      {
        type: "blockquote",
        content: [paragraph(takeaway[0]), paragraph(takeaway[1])],
      },
      ...document.content,
      ...body.flatMap(([heading, ...parts]) => [
        { type: "heading", attrs: { level: 2 }, content: [text(heading)] },
        ...parts.map((value) =>
          Array.isArray(value)
            ? {
                type: "bulletList",
                content: value.map((item) => ({
                  type: "listItem",
                  content: [paragraph(item)],
                })),
              }
            : paragraph(value),
        ),
      ]),
    ],
  };
}
